#!/usr/bin/env python3
"""Writes js/metrics.js: character widths of Times New Roman for the PDF's line breaks.
Only numbers are taken from the fonts, no glyphs. Run with python3 -I check/make-metrics.py"""
import json
from pathlib import Path
from fontTools.ttLib import TTFont

FONTS = Path("/System/Library/Fonts/Supplemental")
FACES = {"regular": "Times New Roman.ttf", "bold": "Times New Roman Bold.ttf",
         "italic": "Times New Roman Italic.ttf", "boldItalic": "Times New Roman Bold Italic.ttf"}
widths, line = {}, None
for name, file in FACES.items():
    font = TTFont(FONTS / file)
    cmap, hmtx, upem = font.getBestCmap(), font["hmtx"], font["head"].unitsPerEm
    row = []
    for byte in range(256):
        try:
            code = ord(bytes([byte]).decode("cp1252"))
        except UnicodeDecodeError:
            code = None
        glyph = cmap.get(code) if code is not None else None
        row.append(round(hmtx[glyph][0] * 1000 / upem) if glyph else 0)
    widths[name] = row
    if name == "regular":
        hhea = font["hhea"]
        line = {k: round(getattr(hhea, a) * 1000 / upem) for k, a in
                (("ascent", "ascent"), ("descent", "descent"), ("leading", "lineGap"))}
        line["descent"] = abs(line["descent"])
out = Path(__file__).resolve().parent.parent / "js/metrics.js"
out.write_text("// Generated by check/make-metrics.py: Times New Roman widths per WinAnsi byte, in 1/1000 em.\n"
               "globalThis.Plain = globalThis.Plain || {};\n"
               f"Plain.metrics = {json.dumps({'line': line, 'widths': widths}, separators=(',', ':'))};\n")
print(line, len(widths["regular"]))
